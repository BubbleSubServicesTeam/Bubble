const DICTS: Record<string, Dict> = { en, es, fr, de, pt, it };

type I18nCtx = {
  lang: string;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nCtx | null>(null);

export function AppLanguageProvider({ children }: { children: React.ReactNode }) {
  const { profile } = useAuth();
  const lang = profile?.native_language ?? 'en';

  const value = useMemo<I18nCtx>(() => {
    const dict = DICTS[lang] ?? en;
    return {
      lang,
      t: (key: string) => dict[key] ?? en[key] ?? key,
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useAppLang(): I18nCtx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useAppLang must be used inside AppLanguageProvider');
  return ctx;
}

export function isSupportedLanguage(code: string | null | undefined): boolean {
  return !!code && DICTS[code] !== undefined && LANGUAGES.some(l => l.code === code);
}
